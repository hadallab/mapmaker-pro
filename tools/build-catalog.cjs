'use strict';
// Builds app/data/catalog.json and copies the official Mapmaker assets into app/assets.
// Sources: the cached official Mapmaker bundle data (packs.json, engine catalog) and the
// animal sprites captured from deeeep.io by the earlier native audit.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..', '..');
const app = path.resolve(__dirname, '..');
const vendor = path.join(root, 'mapmaker-lab', 'vendor');
const engineCatalog = JSON.parse(fs.readFileSync(path.join(root, 'reference-study-2026-10-02', 'engine', 'catalog.json'), 'utf8'));
const packs = JSON.parse(fs.readFileSync(path.join(vendor, 'packs.json'), 'utf8'));
const animalAssets = JSON.parse(fs.readFileSync(path.join(root, 'mapmaker-pro', 'tests', 'fixtures', 'official-animal-assets.json'), 'utf8'));
const animalDir = path.join(root, 'mapmaker-pro', 'tests', 'fixtures', 'animal-assets');

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

const out = path.join(app, 'assets');
fs.rmSync(out, { recursive: true, force: true });

const textures = [];
const hideSpaces = [];
const props = [];
const foods = [];
const sheets = [];

for (const pack of packs) {
  const packDir = path.join(vendor, 'assets', 'packs', String(pack.id));
  for (let i = 1; i <= pack.spritesheets; i++) {
    const json = path.join(packDir, 'spritesheets', i + '.json');
    const png = path.join(packDir, 'spritesheets', i + '.png');
    if (!fs.existsSync(json)) continue;
    copy(png, path.join(out, 'packs', String(pack.id), 'sheet' + i + '.png'));
    const frames = JSON.parse(fs.readFileSync(json, 'utf8')).frames;
    const compact = {};
    for (const [name, f] of Object.entries(frames)) compact[name] = [f.frame.x, f.frame.y, f.frame.w, f.frame.h];
    sheets.push({ pack: pack.id, file: 'packs/' + pack.id + '/sheet' + i + '.png', frames: compact });
  }
  for (const t of pack.textures || []) {
    const src = path.join(packDir, 'textures', t.asset);
    copy(src, path.join(out, 'packs', String(pack.id), 'textures', t.asset));
    textures.push({ id: t.id, pack: pack.id, name: t.name, file: 'packs/' + pack.id + '/textures/' + t.asset });
  }
  for (const h of pack.hideSpaces || []) {
    hideSpaces.push({
      id: h.id, pack: pack.id, packName: pack.name, name: h.name, asset: h.asset,
      width: h.width, height: h.height, anchorX: h.anchor_x, anchorY: h.anchor_y,
      above: !!h.above, canHide: !!h.can_hide, collidable: !!h.collidable, climbable: !!h.climbable
    });
  }
  for (const p of pack.props || []) {
    props.push({
      id: p.id, pack: pack.id, name: p.name, asset: p.asset, width: p.width, height: p.height,
      anchorX: p.anchor_x, anchorY: p.anchor_y, params: p.params || []
    });
  }
  for (const f of pack.foods || []) {
    const src = path.join(packDir, 'food', f.asset);
    if (fs.existsSync(src)) copy(src, path.join(out, 'packs', String(pack.id), 'food', f.asset));
    foods.push({ id: f.id, pack: pack.id, name: f.name, xp: f.xp, file: 'packs/' + pack.id + '/food/' + f.asset });
  }
}

const assetByLevel = new Map(animalAssets.assets.map(a => [a.fishLevel, a]));
const animals = engineCatalog.animals.map((a, index) => {
  const level = a.fishLevel ?? index;
  const asset = assetByLevel.get(level);
  const file = path.join(animalDir, a.name + '.png');
  const available = !!asset && fs.existsSync(file);
  if (available) copy(file, path.join(out, 'animals', a.name + '.png'));
  return {
    level, name: a.name, sizeMultiplier: a.sizeMultiplier,
    clientSideSizeScale: a.clientSideSizeScale ?? null,
    width: asset?.width ?? null, height: asset?.height ?? null,
    habitat: a.habitat, file: available ? 'animals/' + a.name + '.png' : null
  };
});

for (const ui of ['arrow', 'ceiling', 'spawn', 'tppos', 'trigger']) {
  copy(path.join(vendor, 'assets', 'ui', ui + '.png'), path.join(out, 'ui', ui + '.png'));
}

const catalog = {
  source: {
    engine: 'mapmaker.deeeep.io app.a86e76d3.js',
    engineVersion: engineCatalog.constants.version,
    generated: new Date().toISOString().slice(0, 10)
  },
  foodDensity: engineCatalog.constants.foodDensity,
  defaults: engineCatalog.defaults,
  textures: textures.sort((a, b) => a.id - b.id),
  hideSpaces: hideSpaces.sort((a, b) => a.id - b.id),
  props: props.sort((a, b) => a.id - b.id),
  foods: foods.sort((a, b) => a.id - b.id),
  animals,
  sheets
};

fs.mkdirSync(path.join(app, 'src', 'data'), { recursive: true });
fs.writeFileSync(path.join(app, 'src', 'data', 'catalog.json'), JSON.stringify(catalog));
// ES module copy: the renderer imports it directly because fetch() is unavailable on file://.
fs.writeFileSync(path.join(app, 'src', 'data', 'catalog.js'), '// Generated by tools/build-catalog.cjs. Do not edit.\nexport default ' + JSON.stringify(catalog) + ';\n');
console.log('textures', textures.length, 'hideSpaces', hideSpaces.length, 'props', props.length,
  'foods', foods.length, 'animals', animals.length, 'missing animal sprites', animals.filter(a => !a.file).map(a => a.name).join(','));
